/** Default fallback rate for dates outside the PMMS table (decimal) */
const DEFAULT_RATE = 0.0665;

/**
 * Look up the average 30-year fixed mortgage rate for a given date.
 * Extracts YYYY-MM from the input string and returns the PMMS monthly average.
 * Falls back to 0.0665 for dates not in the table.
 *
 * @param dateStr - Date string in YYYY-MM or YYYY-MM-DD format
 * @returns Decimal interest rate (e.g., 0.0312 for 3.12%)
 */
export function getHistoricalRate(dateStr: string): number {
  const key = dateStr.slice(0, 7); // "YYYY-MM-DD" -> "YYYY-MM"
  return PMMS_MONTHLY[key] ?? DEFAULT_RATE;
}
